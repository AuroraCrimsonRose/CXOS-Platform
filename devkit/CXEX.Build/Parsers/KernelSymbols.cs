using System.Buffers.Binary;
using System.Text;

namespace CXEX.Build.Parsers;

/// <summary>A function in the kernel's text: <see cref="Offset"/> bytes from its start.</summary>
public sealed record KernelSymbol(uint Offset, string Name);

/// <summary>
/// Reads the function symbols out of an ELF64 kernel, for the table a panic
/// names its callers with (kernel/diag/ksym.h). Every offset is range-checked:
/// this reads a file, and a malformed one is an error, not a crash.
/// </summary>
public static class KernelSymbols
{
    private const uint ShtSymtab = 2;
    private const int SymSize = 24;
    private const byte SttNotype = 0, SttFunc = 2;

    public static IReadOnlyList<KernelSymbol> Read(byte[] elf)
    {
        if (elf.Length < 64 || elf[0] != 0x7F || elf[1] != 'E' || elf[2] != 'L' || elf[3] != 'F' || elf[4] != 2 || elf[5] != 1)
            throw new InvalidDataException("not a little-endian ELF64 file");

        ulong shoff = U64(elf, 0x28);
        int shentsize = U16(elf, 0x3A), shnum = U16(elf, 0x3C), shstrndx = U16(elf, 0x3E);
        if (shentsize < 64 || shnum == 0 || shoff > (ulong)elf.Length || (ulong)shnum * (ulong)shentsize > (ulong)elf.Length - shoff)
            throw new InvalidDataException("the section table is outside the file");

        int Sh(int i) => (int)shoff + i * shentsize;
        if (shstrndx >= shnum) throw new InvalidDataException("no section-name table");
        var (names, namesLen) = Range(elf, Sh(shstrndx));

        int text = -1, symtab = -1;
        for (int i = 0; i < shnum; i++)
        {
            if (Str(elf, names, namesLen, U32(elf, Sh(i))) == ".text") text = i;
            if (U32(elf, Sh(i) + 4) == ShtSymtab) symtab = i;
        }
        if (text < 0) throw new InvalidDataException("no .text section");
        if (symtab < 0) throw new InvalidDataException("no symbol table: this is a stripped link");

        ulong textAddr = U64(elf, Sh(text) + 0x10), textSize = U64(elf, Sh(text) + 0x20);
        uint strSection = U32(elf, Sh(symtab) + 0x28);
        if (strSection >= shnum) throw new InvalidDataException("the symbol table names no string table");
        var (strs, strsLen) = Range(elf, Sh((int)strSection));
        var (syms, symsLen) = Range(elf, Sh(symtab));

        var found = new List<(uint Offset, bool IsFunc, string Name)>();
        for (long at = 0; at + SymSize <= symsLen; at += SymSize)
        {
            int s = (int)(syms + at);
            byte type = (byte)(elf[s + 4] & 0xF);
            if ((type != SttFunc && type != SttNotype) || U16(elf, s + 6) != text) continue;
            ulong value = U64(elf, s + 8);
            if (value < textAddr || value - textAddr >= textSize) continue;
            string name = Str(elf, strs, strsLen, U32(elf, s));
            if (name.Length == 0 || name.StartsWith(".L", StringComparison.Ordinal) || !IsPlain(name)) continue;
            if (name is "__text_start" or "__text_end") continue;
            found.Add(((uint)(value - textAddr), type == SttFunc, name));
        }

        // At one address, a function's own name rather than a label beside it.
        var ordered = found.OrderBy(f => f.Offset).ThenByDescending(f => f.IsFunc).ThenBy(f => f.Name, StringComparer.Ordinal);
        var result = new List<KernelSymbol>();
        foreach (var f in ordered)
            if (result.Count == 0 || result[^1].Offset != f.Offset) result.Add(new KernelSymbol(f.Offset, f.Name));
        if (result.Count == 0) throw new InvalidDataException("no function symbols in .text");
        return result;
    }

    /// <summary>The table as C, every name terminated, for ksym.h's externs.</summary>
    public static string ToC(IReadOnlyList<KernelSymbol> symbols)
    {
        var sb = new StringBuilder();
        sb.Append("/* Generated by cxk ksyms. */\n#include <stdint.h>\n\n");
        sb.Append($"const uint32_t ksym_count = {symbols.Count};\n\nconst uint32_t ksym_offs[] = {{\n");
        foreach (var s in symbols) sb.Append($"0x{s.Offset:x},\n");
        sb.Append("};\n\nconst uint32_t ksym_name_offs[] = {\n");
        uint at = 0;
        foreach (var s in symbols) { sb.Append($"{at},\n"); at += (uint)s.Name.Length + 1; }
        sb.Append("};\n\nconst char ksym_names[] =\n");
        foreach (var s in symbols) sb.Append($"\"{s.Name}\\0\"\n");
        sb.Append(";\n");
        return sb.ToString();
    }

    private static bool IsPlain(string name) =>
        name.All(c => c is '_' or '.' or '$' || char.IsAsciiLetterOrDigit(c));

    private static (long Offset, long Size) Range(byte[] elf, int sh)
    {
        ulong offset = U64(elf, sh + 0x18), size = U64(elf, sh + 0x20);
        if (offset > (ulong)elf.Length || size > (ulong)elf.Length - offset)
            throw new InvalidDataException("a section is outside the file");
        return ((long)offset, (long)size);
    }

    private static string Str(byte[] elf, long table, long size, uint at)
    {
        if (at >= size) return "";
        long i = table + at, end = table + size;
        long stop = i;
        while (stop < end && elf[stop] != 0) stop++;
        return Encoding.ASCII.GetString(elf, (int)i, (int)(stop - i));
    }

    private static ushort U16(byte[] b, int at) => BinaryPrimitives.ReadUInt16LittleEndian(b.AsSpan(at, 2));
    private static uint U32(byte[] b, int at) => BinaryPrimitives.ReadUInt32LittleEndian(b.AsSpan(at, 4));
    private static ulong U64(byte[] b, int at) => BinaryPrimitives.ReadUInt64LittleEndian(b.AsSpan(at, 8));
}
